namespace PimBurguer.Api.Data;

public static class IntegracaoSql
{
    public const string Criar = """
        CREATE TABLE integracao_estado(chave text PRIMARY KEY, valor text NOT NULL);
        CREATE TABLE integracao_versoes(
          tabela text NOT NULL, chave text NOT NULL, criado_em timestamptz NOT NULL,
          evento_id uuid NOT NULL, PRIMARY KEY(tabela,chave));
        CREATE TABLE integracao_pendentes(
          sequencia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          evento_id uuid NOT NULL UNIQUE, tabela text NOT NULL, chave text NOT NULL,
          operacao text NOT NULL, dados jsonb NOT NULL, criado_em timestamptz NOT NULL,
          tentativas integer NOT NULL DEFAULT 0, ultimo_erro text);
        CREATE OR REPLACE FUNCTION registrar_integracao() RETURNS trigger LANGUAGE plpgsql AS $fn$
        DECLARE registro jsonb; evento uuid; momento timestamptz;
        BEGIN
          IF current_setting('pim.integracao_aplicando',true)='1' THEN RETURN NULL; END IF;
          -- Contadores de tentativas de login e bloqueio temporário são locais.
          IF TG_TABLE_NAME='usuarios' AND TG_OP='UPDATE' THEN
            IF (to_jsonb(NEW)-'falhas_login'-'bloqueado_ate')=(to_jsonb(OLD)-'falhas_login'-'bloqueado_ate') THEN RETURN NULL; END IF;
          END IF;
          IF TG_OP='DELETE' THEN registro=to_jsonb(OLD); ELSE registro=to_jsonb(NEW); END IF;
          evento=gen_random_uuid(); momento=clock_timestamp();
          INSERT INTO integracao_pendentes(evento_id,tabela,chave,operacao,dados,criado_em)
            VALUES(evento,TG_TABLE_NAME,registro->>'id',TG_OP,registro,momento);
          INSERT INTO integracao_versoes(tabela,chave,criado_em,evento_id)
            VALUES(TG_TABLE_NAME,registro->>'id',momento,evento)
            ON CONFLICT(tabela,chave) DO UPDATE SET criado_em=EXCLUDED.criado_em,evento_id=EXCLUDED.evento_id;
          RETURN NULL;
        END $fn$;
        DO $triggers$
        DECLARE t text;
        BEGIN
          FOREACH t IN ARRAY ARRAY['produtos','usuarios','cupons','pedidos','itens_pedido','usos_cupom','movimentacoes_pedido']
          LOOP
            EXECUTE format('CREATE TRIGGER integracao_alteracao AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION registrar_integracao()', t);
          END LOOP;
        END $triggers$;
        """;
    public const string Remover = """
        DO $triggers$
        DECLARE t text;
        BEGIN
          FOREACH t IN ARRAY ARRAY['produtos','usuarios','cupons','pedidos','itens_pedido','usos_cupom','movimentacoes_pedido']
          LOOP EXECUTE format('DROP TRIGGER IF EXISTS integracao_alteracao ON %I', t); END LOOP;
        END $triggers$;
        DROP FUNCTION registrar_integracao();
        DROP TABLE integracao_pendentes,integracao_versoes,integracao_estado;
        """;
}
